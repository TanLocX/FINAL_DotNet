SET XACT_ABORT ON;
SET NOCOUNT ON;

BEGIN TRY
    BEGIN TRANSACTION;

    -- So sánh byte UTF-16 của dữ liệu lỗi để script không chứa chuỗi mojibake hiển thị.
    UPDATE dbo.HoaDon
    SET PhuongThucThanhToan = N'Chuyển khoản'
    WHERE CONVERT(VARBINARY(MAX), PhuongThucThanhToan) =
          0x4300680075007900E100BB0092016E0020006B0068006F00E100BA00A3006E00;

    UPDATE dbo.HoaDon
    SET PhuongThucThanhToan = N'Tiền mặt'
    WHERE CONVERT(VARBINARY(MAX), PhuongThucThanhToan) =
          0x54006900E100BB0081006E0020006D00E100BA00B7007400;

    UPDATE dbo.NhatKyGuiEmail
    SET TieuDe = N'PNJ - Xác nhận hóa đơn HD000010'
    WHERE CONVERT(VARBINARY(MAX), TieuDe) =
          0x50004E004A0020002D0020005800C300A100630020006E006800E100BA00AD006E0020006800C300B30061002000C4001820C600A1006E00200048004400300030003000300031003000;

    UPDATE dbo.PhieuBaoHanh
    SET NoiDungBaoHanh = N'Làm sạch và chỉnh size nhẫn'
    WHERE CONVERT(VARBINARY(MAX), NoiDungBaoHanh) =
          0x4C00C300A0006D0020007300E100BA00A1006300680020007600C300A000200063006800E100BB0030206E0068002000730069007A00650020006E006800E100BA00AB006E00;

    UPDATE dbo.PhieuNhap
    SET GhiChu = N'Nhập bổ sung trang sức kim cương tháng 9'
    WHERE CONVERT(VARBINARY(MAX), GhiChu) =
          0x4E006800E100BA00AD00700020006200E100BB0022202000730075006E00670020007400720061006E00670020007300E100BB00A900630020006B0069006D0020006300C600B000C600A1006E006700200074006800C300A1006E00670020003900;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO

PRINT N'Đã sửa các giá trị tiếng Việt bị lưu sai mã hóa.';
